import express from "express";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { access } from "node:fs/promises";
import mongoose from "mongoose";
import { disposableReplica } from "./disposableReplica.js";
import { fixtureConfig, fixtureMailbox, seedFixture } from "./demoFixture.js";

const dist = fileURLToPath(new URL("../../Frontend/demo-dist/", import.meta.url));
try {
  await access(path.join(dist, "index.html"));
} catch (error) {
  if (error.code !== "ENOENT") throw error;
  throw new Error("Build the local demo first with npm --prefix Frontend run build:demo.");
}
const replica = await disposableReplica();
const port = Number(process.env.DEMO_PORT || 4180);
fixtureConfig(replica, "http://localhost:" + port);
const mail = fixtureMailbox();
let server;
async function close() {
  server?.closeAllConnections();
  if (server?.listening) await new Promise(r => server.close(r));
  mail.close(); await mongoose.disconnect(); await replica.close();
}
try {
  const { default: app } = await import("../app.js");
  await mongoose.connect(replica.uri);
  await Promise.all(Object.values(mongoose.models).map(m => m.init()));
  await seedFixture();
  app.get("/demo-inbox", (req, res) => {
    // Links and recipients are generated by this process. Render using DOM text nodes.
    res.set("Cache-Control", "no-store").type("html").send('<title>Demo mailbox</title><h1>Local demo mailbox</h1><p>Refresh after requesting a link.</p><ul id="mail"></ul><script>fetch("/demo-messages").then(r=>r.json()).then(rows=>{for(const row of rows){const a=document.createElement("a");a.href=row.url;a.textContent=row.to;const li=document.createElement("li");li.append(a);mail.append(li)}})</script>');
  });
  app.get("/demo-messages", (req, res) => res.set("Cache-Control", "no-store").json(mail.messages));
  app.use(express.static(dist));
  app.get("/{*route}", (req, res) => res.sendFile(path.join(dist, "index.html")));
  server = app.listen(port, "127.0.0.1", () => console.log("Synthetic demo ready at http://localhost:" + port));
  server.on("error", async () => { await close(); process.exitCode = 1; });
  for (const signal of ["SIGINT", "SIGTERM"]) process.once(signal, async () => { await close(); process.exit(0); });
} catch (error) { await close(); throw error; }
